"""BigQuery infrastructure specs generated from the policy (SPEC.md sections 15.1 to 15.6 and 30.3.8).

Templates use `{project}` and `{user}` placeholders, filled by `pv setup gcp`. Nothing here talks to Google Cloud.
The project is shared with three other repos, so every name comes from the policy's `naming.prefix` and every grant
is dataset- or resource-scoped: the only project-level role is roles/bigquery.jobUser (it creates jobs and reads no
data). The executor holds dataOwner on this repo's datasets, the time travel role on the three row-policy datasets,
Fine-Grained Reader on the six tags and roles/datacatalog.viewer on the taxonomy resource, and nothing on any other
dataset of the project.
"""

from __future__ import annotations

import json

from peoplevault.policy.model import Policy

GENERATED = "Generated by `pv policy compile` from policy/policy.yaml. Do not edit."
MASK_EXPRESSION = {"mask_nullify": "ALWAYS_NULL", "mask_date_year": "DATE_YEAR_MASK"}
APIS = ["bigquery.googleapis.com", "datacatalog.googleapis.com", "bigquerydatapolicy.googleapis.com", "iamcredentials.googleapis.com", "iam.googleapis.com"]


def sa(name: str) -> str:
    return f"{name}@{{project}}.iam.gserviceaccount.com"


def service_accounts(policy: Policy) -> list[dict]:
    out = [{"account_id": p.bq_identity, "display_name": f"PeopleVault purpose reader: {name}", "key": False} for name, p in policy.purposes.items()]
    out.append({"account_id": policy.gateway_sa, "display_name": "PeopleVault gateway (Token Creator on the purpose readers only)", "key": True})
    out.append({"account_id": policy.executor_sa, "display_name": "PeopleVault executor (dbt, loaders, erasure, verification)", "key": False})
    return out


def datasets(policy: Policy) -> list[dict]:
    out = []
    for d in policy.datasets.data:
        out.append({"dataset": d, "location": "US", "max_time_travel_hours": policy.datasets.max_time_travel_hours,
                    "access": [{"role": "OWNER", "member": f"serviceAccount:{sa(policy.executor_sa)}"}]})
    for name, p in policy.purposes.items():
        out.append({"dataset": policy.purpose_dataset(name), "location": "US", "max_time_travel_hours": None,
                    "access": [{"role": "OWNER", "member": f"serviceAccount:{sa(policy.executor_sa)}"}, {"role": "READER", "member": f"serviceAccount:{sa(p.bq_identity)}"}]})
    # Created by setup (as the owner) because the executor holds no project-level role that creates datasets: the
    # ceiling probes' temporary views (emptied after each run) and the eval's planted "new dataset" residue.
    for d in (policy.probe_dataset, policy.scratch_dataset):
        out.append({"dataset": d, "location": "US", "max_time_travel_hours": None, "access": [{"role": "OWNER", "member": f"serviceAccount:{sa(policy.executor_sa)}"}]})
    return out


def taxonomy(policy: Policy) -> dict:
    return {"display_name": policy.naming.prefix, "location": "us", "activated_policy_types": ["FINE_GRAINED_ACCESS_CONTROL"],
            "policy_tags": [{"display_name": c, "description": f"PeopleVault data class {c}"} for c in policy.data_classes.tagged]}


def fine_grained_readers(policy: Policy) -> dict[str, list[str]]:
    out: dict[str, list[str]] = {}
    for cls in policy.data_classes.tagged:
        members = [f"serviceAccount:{sa(p.bq_identity)}" for name, p in policy.purposes.items() if policy.visibility[name][cls] == "allow"]
        out[cls] = [*members, f"serviceAccount:{sa(policy.executor_sa)}"]
    return out


def data_policies(policy: Policy) -> list[dict]:
    out = []
    for cls in policy.data_classes.tagged:
        by_expr: dict[str, list[str]] = {}
        for name, p in policy.purposes.items():
            vis = policy.visibility[name][cls]
            if vis in MASK_EXPRESSION:
                by_expr.setdefault(MASK_EXPRESSION[vis], []).append(f"serviceAccount:{sa(p.bq_identity)}")
        for expr, grantees in sorted(by_expr.items()):
            out.append({"data_policy_id": policy.data_policy_id(cls, expr), "policy_tag": cls, "data_policy_type": "DATA_MASKING_POLICY",
                        "predefined_expression": expr, "grantees": grantees})
    return out


def custom_roles(policy: Policy) -> list[dict]:
    return [{"role_id": policy.time_travel_role, "title": "PeopleVault time travel reader",
             "description": "Read time travel of tables that have or had row access policies (residual checks).",
             "permissions": ["bigquery.rowAccessPolicies.overrideTimeTravelRestrictions"], "stage": "GA",
             "grants": [{"dataset": d, "member": f"serviceAccount:{sa(policy.executor_sa)}"} for d in policy.datasets.authorized_sources]}]


def iam_bindings(policy: Policy) -> dict:
    project = []
    for p in policy.purposes.values():
        project.append({"role": "roles/bigquery.jobUser", "member": f"serviceAccount:{sa(p.bq_identity)}"})
    # shared project: no project-level data role for the executor (it would read the other repos' datasets)
    project.append({"role": "roles/bigquery.jobUser", "member": f"serviceAccount:{sa(policy.executor_sa)}"})
    token_creator = [{"service_account": sa(p.bq_identity), "role": "roles/iam.serviceAccountTokenCreator", "member": f"serviceAccount:{sa(policy.gateway_sa)}"} for p in policy.purposes.values()]
    token_creator += [{"service_account": sa(x), "role": "roles/iam.serviceAccountTokenCreator", "member": "user:{user}"} for x in [policy.executor_sa, *[p.bq_identity for p in policy.purposes.values()]]]
    taxonomy_grants = [{"role": "roles/datacatalog.viewer", "member": f"serviceAccount:{sa(policy.executor_sa)}"}]
    return {"apis": APIS, "project": project, "service_account": token_creator, "taxonomy": taxonomy_grants, "fine_grained_reader": fine_grained_readers(policy)}


def generate(policy: Policy) -> dict[str, str]:
    def dump(v) -> str:
        return json.dumps({"_generated": GENERATED, "spec": v}, indent=2) + "\n"

    return {
        "infra/bigquery/service_accounts.json": dump(service_accounts(policy)),
        "infra/bigquery/datasets.json": dump(datasets(policy)),
        "infra/bigquery/taxonomy.json": dump(taxonomy(policy)),
        "infra/bigquery/data_policies.json": dump(data_policies(policy)),
        "infra/bigquery/custom_roles.json": dump(custom_roles(policy)),
        "infra/bigquery/iam_bindings.json": dump(iam_bindings(policy)),
    }
