"""SQL generation from the policy (SPEC.md sections 9.3 and 15.7).

Emits, for both dialects from one policy:
- dbt purpose view models (`pipelines/dbt/models/purpose/<purpose>/`), with masking through `pv_mask()` (BigQuery:
  raw column, masked by the policy tag's data policy; DuckDB: expression in the view) and the restricted and
  terminated filters in the view SQL (BigQuery also enforces the restricted filter with row access policies);
- the `create_purpose_routines()` macro (BigQuery table functions, DuckDB table macros);
- the `pv_row_access_policies()` post-hook macro (BigQuery only) and `pv_direct_identifier_columns()`;
- the named query SQL that the Worker (BigQuery REST) and the local shim (DuckDB) run.
"""

from __future__ import annotations

from peoplevault.policy.model import Policy, QueryDef

GENERATED = "Generated by `pv policy compile` from policy/policy.yaml. Do not edit."
PURPOSE_MODELS_DIR = "pipelines/dbt/models/purpose"
ROUTINES_MACRO = "pipelines/dbt/macros/purpose_routines.sql"
ROW_ACCESS_MACRO = "pipelines/dbt/macros/row_access.sql"
POLICY_COLUMNS_MACRO = "pipelines/dbt/macros/policy_columns.sql"

BQ_TYPES = {"string": "STRING", "string_array": "ARRAY<STRING>", "date": "DATE", "int": "INT64"}


def _view_where(policy: Policy, purpose: str, source: str) -> list[str]:
    p = policy.purposes[purpose]  # type: ignore[index]
    if source == "headcount_monthly":
        return []  # aggregate built without the restricted population; no row-level columns
    out = []
    if p.restricted_population == "exclude":
        out.append("not is_restricted")
    if p.terminated == "exclude" and source == "profile_base":
        out.append("employment_status = 'active'")
    return out


def purpose_view_sql(policy: Policy, purpose: str, view: str) -> str:
    v = policy.purpose_views[purpose][view]  # type: ignore[index]
    dataset = policy.purpose_dataset(purpose)
    cols = []
    for col in v.columns:
        vis = policy.visibility_of(purpose, col)
        cols.append(f"  {{{{ pv_mask('{col}', '{vis}') }}}} as {col}" if vis != "allow" else f"  {col}")
    where = _view_where(policy, purpose, v.source)
    sources = ", ".join(f"'{d}'" for d in policy.datasets.authorized_sources)
    lines = [
        f"-- {GENERATED}",
        "{{ config(",
        "    materialized='view',",
        f"    schema='{dataset}',",
        f"    alias='{view}',",
        f"    grant_access_to=pv_grant_access_to([{sources}])",
        ") }}",
        "select",
        ",\n".join(cols),
        f"from {{{{ ref('{v.source}') }}}}",
    ]
    if where:
        lines.append("where " + "\n  and ".join(where))
    return "\n".join(lines) + "\n"


def purpose_schema_yml(policy: Policy, purpose: str) -> str:
    lines = [f"# {GENERATED}", "version: 2", "models:"]
    for view, v in policy.purpose_views[purpose].items():  # type: ignore[index]
        lines.append(f"  - name: {purpose}__{view}")
        lines.append(f"    description: \"Purpose view {view} for {purpose} (source {v.source}).\"")
        if purpose == "workforce_analytics":
            lines.append("    data_tests:")
            lines.append("      - no_direct_identifiers")
        lines.append("    columns:")
        for col in v.columns:
            cls = policy.column_class[col]
            lines.append(f"      - name: {col}")
            lines.append(f"        description: \"class {cls}, visibility {policy.visibility_of(purpose, col)}\"")
    return "\n".join(lines) + "\n"


def _filter_sql(f, dialect: str, prefix: str) -> str:
    p = prefix + f.param
    if f.op == "eq":
        return f"{f.column} = {p}"
    if f.op == "in_array":
        return f"{f.column} in unnest({p})" if dialect == "bigquery" else f"list_contains({p}, {f.column})"
    if f.op == "prefix_any_ci":
        return "(" + " or ".join(f"starts_with(lower({c}), lower({p}))" for c in f.columns or []) + ")"
    raise ValueError(f.op)


def routine_sql(policy: Policy, purpose: str, q: QueryDef, dialect: str) -> str:
    assert q.function is not None
    dataset = policy.purpose_dataset(purpose)
    cols = ", ".join(q.columns)
    where = " and ".join(_filter_sql(f, dialect, "p_") for f in q.filters)
    tail = ""
    if q.order_by:
        tail += " order by " + ", ".join(q.order_by)
    if q.limit:
        tail += f" limit {q.limit}"
    if dialect == "bigquery":
        params = ", ".join(f"p_{name} {BQ_TYPES[t]}" for name, t in q.function.params.items())
        return (
            f"create or replace table function `{{project}}.{dataset}.{q.function.name}`({params}) as ("
            f"select {cols} from `{{project}}.{dataset}.{q.function.view}` where {where}{tail})"
        )
    params = ", ".join(f"p_{name}" for name in q.function.params)
    return f"create or replace macro {dataset}.{q.function.name}({params}) as table select {cols} from {dataset}.{q.function.view} where {where}{tail}"


def query_sql(policy: Policy, purpose: str, q: QueryDef, dialect: str) -> str:
    """Named query SQL. DuckDB uses $name parameters; BigQuery uses @name and a `{project}` placeholder."""
    prefix = "@" if dialect == "bigquery" else "$"
    dataset = policy.purpose_dataset(purpose)
    cols = ", ".join(q.columns)
    where: list[str] = []
    if q.function:
        args = ", ".join(prefix + name for name in q.function.params)
        rel = f"`{{project}}.{dataset}.{q.function.name}`({args})" if dialect == "bigquery" else f"{dataset}.{q.function.name}({args})"
    else:
        rel = f"`{{project}}.{dataset}.{q.view}`" if dialect == "bigquery" else f"{dataset}.{q.view}"
        where.extend(_filter_sql(f, dialect, prefix) for f in q.filters)
    if q.paged_by:
        where.append(f"({prefix}cursor = '' or {q.paged_by} > {prefix}cursor)")
    sql = f"select {cols} from {rel}"
    if where:
        sql += " where " + " and ".join(where)
    order = q.order_by or ([q.paged_by] if q.paged_by else None)
    if order:
        sql += " order by " + ", ".join(order)
    if q.paged_by:
        sql += f" limit {prefix}limit"
    return sql


def routines_macro(policy: Policy) -> str:
    entries = []
    for purpose, qs in policy.queries.items():
        for q in qs.values():
            if q.function:
                entries.append((policy.purpose_dataset(purpose), q.function.view, routine_sql(policy, purpose, q, "bigquery"), routine_sql(policy, purpose, q, "duckdb")))
    lines = [
        f"{{#- {GENERATED}",
        "    on-run-end: create the purpose table functions (BigQuery TABLE FUNCTION, DuckDB table macro) over the purpose",
        "    views. Skipped for a routine whose view does not exist yet (the snapshot replay runs before the first build).",
        "    The functions read only their own purpose dataset, whose views are authorized on the source datasets. -#}",
        "{% macro create_purpose_routines() %}",
        "  {%- if execute -%}",
        "  {%- set routines = [",
    ]
    for i, (dataset, view, bq, duck) in enumerate(entries):
        comma = "," if i < len(entries) - 1 else ""
        lines.append(f"    {{'dataset': '{dataset}', 'view': '{view}', 'bigquery': {bq!r}, 'duckdb': {duck!r}}}{comma}")
    lines += [
        "  ] -%}",
        "  {%- for r in routines -%}",
        "    {%- set rel = adapter.get_relation(database=target.database, schema=r['dataset'], identifier=r['view']) -%}",
        "    {%- if rel is not none -%}",
        "      {%- if target.type == 'bigquery' -%}",
        "        {%- do run_query(r['bigquery'] | replace('{project}', target.project)) -%}",
        "      {%- else -%}",
        "        {%- do run_query(r['duckdb']) -%}",
        "      {%- endif -%}",
        "    {%- endif -%}",
        "  {%- endfor -%}",
        "  {%- endif -%}",
        "{% endmacro %}",
    ]
    return "\n".join(lines) + "\n"


def row_access_macro(policy: Policy) -> str:
    full = [p.bq_identity for p in policy.purposes.values() if p.restricted_population == "include"] + [policy.executor_sa]
    limited = [p.bq_identity for p in policy.purposes.values() if p.restricted_population == "exclude"]

    def grantees(names: list[str]) -> str:
        return ", ".join(f'"serviceAccount:{n}@{{{{ target.project }}}}.iam.gserviceaccount.com"' for n in names)

    return "\n".join([
        f"{{#- {GENERATED}",
        "    Row access policies (BigQuery only), re-issued by a post-hook after every build of a core, snapshot or",
        f"    row-level mart model. Principals outside every grantee list see no rows, so {policy.executor_sa} is in rap_full.",
        "    Protected tables are never replaced (ADR 0006), so the policies are never dropped. -#}",
        "{% macro pv_row_access_policies() -%}",
        "{%- if target.type == 'bigquery' -%}",
        f"create or replace row access policy rap_full on {{{{ this }}}} grant to ({grantees(full)}) filter using (true);",
        f"create or replace row access policy rap_non_restricted on {{{{ this }}}} grant to ({grantees(limited)}) filter using (is_restricted = false)",
        "{%- endif -%}",
        "{%- endmacro %}",
    ]) + "\n"


def policy_columns_macro(policy: Policy) -> str:
    cols = ", ".join(f"'{c}'" for c in policy.columns["direct_identifier"])
    tagged = {cls: policy.columns[cls] for cls in policy.data_classes.tagged}
    lines = [
        f"{{#- {GENERATED} -#}}",
        "{% macro pv_direct_identifier_columns() -%}",
        f"  {{{{ return([{cols}]) }}}}",
        "{%- endmacro %}",
        "",
        "{% macro pv_tagged_columns() -%}",
        "  {{ return({",
    ]
    items = list(tagged.items())
    for i, (cls, cs) in enumerate(items):
        comma = "," if i < len(items) - 1 else ""
        lines.append(f"    '{cls}': [{', '.join(repr(c) for c in cs)}]{comma}")
    lines += ["  }) }}", "{%- endmacro %}"]
    return "\n".join(lines) + "\n"


def generate(policy: Policy) -> dict[str, str]:
    out: dict[str, str] = {}
    for purpose, views in policy.purpose_views.items():
        for view in views:
            out[f"{PURPOSE_MODELS_DIR}/{purpose}/{purpose}__{view}.sql"] = purpose_view_sql(policy, purpose, view)
        out[f"{PURPOSE_MODELS_DIR}/{purpose}/schema.yml"] = purpose_schema_yml(policy, purpose)
    out[ROUTINES_MACRO] = routines_macro(policy)
    out[ROW_ACCESS_MACRO] = row_access_macro(policy)
    out[POLICY_COLUMNS_MACRO] = policy_columns_macro(policy)
    return out
