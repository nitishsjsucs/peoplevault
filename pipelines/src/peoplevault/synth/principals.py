"""Opaque principal ids and the D1 seed (principals, identity_map, legal_holds).

Principal ids never derive from employee data: `hrbp-01`..`hrbp-06`, `mgr-001`..`mgr-120` (seeded shuffle, not
employee id order), `analyst-01`..`analyst-04`, `privacy-01`, `privacy-02`, plus the system principal
`pv-executor-local`. The hash-chained audit log stores only these ids, so it never needs scrubbing (ADR 0005).
"""

from __future__ import annotations

import json
from dataclasses import dataclass

from peoplevault.pseudo import Pseudonymizer
from peoplevault.synth import counts as C
from peoplevault.synth.population import HOLD_MATTERS, Population, rng

CREATED_AT = "2026-09-01T00:00:00Z"
HOLD_PLACED_AT = "2026-09-15T00:00:00Z"
HOLD_REASON = {"LH-2026-001": "Preservation notice for matter LH-2026-001", "LH-2026-002": "Preservation notice for matter LH-2026-002"}
EXECUTOR_LOCAL = "pv-executor-local"


@dataclass(frozen=True)
class PrincipalRow:
    id: str
    kind: str
    persona: str | None
    system_role: str | None
    email: str | None
    service_client_id: str | None
    employee_id: str | None
    org_units: list[str]
    status: str = "active"


def build_principals(pop: Population) -> list[PrincipalRow]:
    r = rng("principal-ids")
    rows: list[PrincipalRow] = []

    def human(pid: str, persona: str, e_id: str, units: list[str] | None = None) -> PrincipalRow:
        return PrincipalRow(pid, "human", persona, None, pop.employees[e_id].work_email, None, e_id, units or [])

    for i, e_id in enumerate(r.sample(pop.hr_partners, len(pop.hr_partners)), start=1):
        rows.append(human(f"hrbp-{i:02d}", "hr_partner", e_id, pop.hr_partner_units[e_id]))
    managers = sorted(e for e, emp in pop.employees.items() if emp.is_manager)
    assert len(managers) == C.MANAGERS
    for i, e_id in enumerate(r.sample(managers, len(managers)), start=1):
        rows.append(human(f"mgr-{i:03d}", "manager", e_id))
    for i, e_id in enumerate(r.sample(pop.analysts, len(pop.analysts)), start=1):
        rows.append(human(f"analyst-{i:02d}", "people_analyst", e_id))
    for i, e_id in enumerate(r.sample(pop.privacy_officers, len(pop.privacy_officers)), start=1):
        rows.append(human(f"privacy-{i:02d}", "privacy_officer", e_id))
    rows.append(PrincipalRow(EXECUTOR_LOCAL, "system", None, "executor", None, EXECUTOR_LOCAL, None, []))
    assert len(rows) == C.D1_PRINCIPALS
    return rows


def sql_literal(v: object) -> str:
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "1" if v else "0"
    if isinstance(v, int | float):
        return repr(v)
    return "'" + str(v).replace("'", "''") + "'"


def seed_sql(pop: Population, principals: list[PrincipalRow], ps: Pseudonymizer) -> str:
    lines = ["-- Generated by `pv synth`. D1 seed: principals, identity_map, legal_holds."]
    for p in principals:
        vals = [p.id, p.kind, p.persona, p.system_role, p.email, p.service_client_id, p.employee_id, json.dumps(p.org_units), p.status, CREATED_AT]
        lines.append(
            "INSERT INTO principals (id, kind, persona, system_role, email, service_client_id, employee_id, org_units, status, created_at) VALUES ("
            + ", ".join(sql_literal(v) for v in vals) + ");"
        )
    for e_id in pop.ids():
        f = pop.final(e_id)
        refs = ps.all(e_id)
        vals = [
            e_id, f.work_email, f.full_name, refs["employee_ref"], refs["warehouse_key"], refs["analytics_id"], refs["subject_ref"],
            f.manager_id, "active" if f.termination_date is None else "terminated",
            f.termination_date.isoformat() if f.termination_date else None,
        ]
        lines.append(
            "INSERT INTO identity_map (employee_id, work_email, full_name, employee_ref, warehouse_key, analytics_id, subject_ref, manager_employee_id, employment_status, termination_date) VALUES ("
            + ", ".join(sql_literal(v) for v in vals) + ");"
        )
    n = 0
    for matter in HOLD_MATTERS:
        for e_id in pop.holds[matter]:
            n += 1
            vals = [f"hold-{n:03d}", matter, ps.pseudonym("subject_ref", e_id), HOLD_REASON[matter], "privacy-01", HOLD_PLACED_AT, None, None]
            lines.append(
                "INSERT INTO legal_holds (id, matter_id, subject_ref, reason, placed_by, placed_at, released_at, released_by) VALUES ("
                + ", ".join(sql_literal(v) for v in vals) + ");"
            )
    return "\n".join(lines) + "\n"
